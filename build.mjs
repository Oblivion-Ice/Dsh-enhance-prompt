/**
 * dsh-enhance-prompt build pipeline (M1.5).
 *
 * One invocation produces the complete `lib/` directory:
 *
 * - `lib/host/**` and `lib/shared/**`: TypeScript compiled per file to ESM.
 *   Relative `.ts` specifiers are rewritten to `.js` after compilation because
 *   esbuild does not implement TypeScript's `rewriteRelativeImportExtensions`.
 * - `lib/index.js`: the package entry, generated rather than hand-written.
 * - `lib/client.js`: the browser bundle wrapped in the DSH module-loader
 *   envelope. Only `react` stays external; every other runtime dependency
 *   (including zod) is inlined.
 *
 * `lib/` is fully generated and ignored by version control; do not edit it.
 */

import { build } from 'esbuild'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.dirname(fileURLToPath(import.meta.url))
const src = path.join(root, 'src')
const lib = path.join(root, 'lib')
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))
const CLIENT_ENTRY = path.join(src, 'client', 'index.tsx')
const MAX_CLIENT_BYTES = 200 * 1024

/** Turn `./foo.ts` into `./foo.js` in emitted ESM without touching package imports. */
function rewriteRelativeTsSpecifiers(code) {
  return code.replace(/(\bfrom\s*["'])(\.{1,2}\/[^"']+)\.ts(["'])/g, '$1$2.js$3')
}

/** Recursively list files under `dir`, sorted for deterministic output. */
function listFiles(dir) {
  if (!fs.existsSync(dir)) return []
  const out = []
  for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) out.push(...listFiles(full))
    else out.push(full)
  }
  return out
}

const hostEntries = [
  ...fs.readdirSync(path.join(src, 'host'))
    .filter(name => name.endsWith('.ts'))
    .sort()
    .map(name => path.join(src, 'host', name)),
  path.join(src, 'shared', 'protocol.ts'),
]

fs.rmSync(lib, { recursive: true, force: true })
fs.mkdirSync(lib, { recursive: true })

await build({
  entryPoints: hostEntries,
  outbase: src,
  outdir: lib,
  bundle: false,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  sourcemap: false,
  legalComments: 'none',
  logLevel: 'warning',
})

for (const file of listFiles(lib).filter(file => file.endsWith('.js'))) {
  const before = fs.readFileSync(file, 'utf8')
  const after = rewriteRelativeTsSpecifiers(before)
  if (after !== before) fs.writeFileSync(file, after)
}

fs.writeFileSync(
  path.join(lib, 'index.js'),
  "/** Package entry, generated by build.mjs. */\nexport { apply, inject, Config } from './host/index.js'\n",
)

/** Module-loader envelope. The CJS body only executes when the loader materializes the factory. */
const banner = `window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
`
const footer = `
    return module.exports;
  },
});
`

await build({
  entryPoints: [CLIENT_ENTRY],
  outfile: path.join(lib, 'client.js'),
  bundle: true,
  platform: 'browser',
  format: 'cjs',
  target: 'es2020',
  external: ['react'],
  jsx: 'transform',
  jsxFactory: 'React.createElement',
  jsxFragment: 'React.Fragment',
  minify: true,
  charset: 'utf8',
  legalComments: 'none',
  sourcemap: false,
  banner: { js: banner },
  footer: { js: footer },
  logLevel: 'warning',
})

const clientBytes = fs.statSync(path.join(lib, 'client.js')).size
const emitted = listFiles(lib).map(file => path.relative(root, file).replaceAll('\\', '/'))
console.log(`built ${emitted.length} files in lib/`)
for (const file of emitted) console.log(`  ${file}`)
console.log(`client.js: ${clientBytes} bytes (limit ${MAX_CLIENT_BYTES})`)
if (clientBytes > MAX_CLIENT_BYTES) {
  console.warn(`[dsh-enhance-prompt] client.js exceeds the 200 KB budget; report its composition before shipping`)
  process.exitCode = 2
}
